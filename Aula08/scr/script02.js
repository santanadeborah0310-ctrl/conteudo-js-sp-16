
// Funções

// Funções de Multiplicação
function multiplicar(a, b) {
    return a * b;
}

console.log(multiplicar(10, 5));
console.log(multiplicar(2, 20));
console.log(multiplicar(10, 10));
console.log(multiplicar(7, 7));

// Funções de Soma
function somar(a, b) {
    return a + b;
}

console.log(somar(74, 20));
console.log(somar(34, 30));

// Funções de Subtração
function subtrair(a, b) {
    return a - b;
}

console.log(subtrair(13, 4));
console.log(subtrair(25, 7));
