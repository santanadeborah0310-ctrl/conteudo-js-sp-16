// Exercício 5: Caucule a aárea de um retângulo.

alert("Área de Retângulo");

let larguraRetângulo = parseFloat(prompt("Informe o valor da largura do retângulo em centimetro:"));

let alturaRetângulo = parseFloat(prompt("Imforme a altura do retângulo em centímetros:"));

let areaRetângulo = larguraRetângulo * alturaRetângulo;

alert("A área total do retângulo de largura" + larguraRetângulo + "cm e altura" + alturaRetângulo + "cm é:" + areaRetângulo + "cm² ");